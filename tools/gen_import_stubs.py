#!/usr/bin/env python3
"""
Generates ARRecomp/kernel/imports/unimplemented.cpp with a logging stub for every import the recompiled code
references that has no AR_IMPORT implementation yet. Run it after implementing imports or regenerating the code.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
shared = (root / "ARRecompLib" / "ppc" / "ppc_recomp_shared.h").read_text()
imports = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", shared)))

output = root / "ARRecomp" / "kernel" / "imports" / "unimplemented.cpp"
implemented = set()
for source in (root / "ARRecomp").rglob("*.cpp"):
    if source == output:
        continue
    text = source.read_text(encoding="utf-8")
    implemented.update(re.findall(r"AR_IMPORT\((\w+)\)", text))
    implemented.update(re.findall(r"PPC_FUNC\(__imp__(\w+)\)", text))

missing = [name for name in imports if name not in implemented]

lines = [
    "// Generated by tools/gen_import_stubs.py. Do not edit; implement imports with AR_IMPORT instead.",
    "#include <stdafx.h>",
    "#include <kernel/imports.h>",
    "",
    "// Logs the first call and returns 0 in r3.",
    "#define AR_IMPORT_STUB(name) \\",
    "    PPC_FUNC(__imp__##name) \\",
    "    { \\",
    "        static std::atomic<bool> logged; \\",
    "        if (!logged.exchange(true)) \\",
    "            LOGF_WARNING(\"unimplemented import \" #name \" called from 0x{:08X}\", uint32_t(ctx.lr)); \\",
    "        ctx.r3.u64 = 0; \\",
    "    }",
    "",
]
lines += [f"AR_IMPORT_STUB({name});" for name in missing]
output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(imports)} imports, {len(implemented & set(imports))} implemented, {len(missing)} stubbed")
